"""Generate draw-sized WebP copies and a content-addressed manifest. Requires Pillow."""
from pathlib import Path
from PIL import Image, ImageOps
import hashlib
import json

root = Path(__file__).resolve().parents[1]
public = root / 'public'
output = public / 'hero-images' / 'summon'
output.mkdir(parents=True, exist_ok=True)
sources = sorted((public / 'hero-images' / 'full-body').glob('*.png'))
sources += [public / 'others/full-body/shamozhinu.png', public / 'hero-images/avatars/醉枕刀.png']
manifest = {}
original_bytes = optimized_bytes = 0
for source in sources:
    if not source.exists():
        raise FileNotFoundError(source)
    with Image.open(source) as image:
        image = ImageOps.exif_transpose(image)
        image.thumbnail((768, 768), Image.Resampling.LANCZOS)
        image = image.convert('RGBA' if 'A' in image.getbands() else 'RGB')
        import io
        encoded = io.BytesIO()
        image.save(encoded, 'WEBP', quality=86, method=6)
    data = encoded.getvalue()
    filename = hashlib.sha256(data).hexdigest()[:16] + '.webp'
    (output / filename).write_bytes(data)
    manifest['/' + source.relative_to(public).as_posix()] = '/hero-images/summon/' + filename
    original_bytes += source.stat().st_size
    optimized_bytes += len(data)
(root / 'src/data/summon-image-manifest.ts').write_text(
    '// Generated by scripts/optimize-summon-images.py; original portraits remain unchanged.\n'
    + 'export const SUMMON_IMAGE_MANIFEST: Record<string, string> = '
    + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
print(json.dumps({'images': len(manifest), 'originalBytes': original_bytes,
                  'optimizedBytes': optimized_bytes, 'reductionPercent': round(100 * (1 - optimized_bytes / original_bytes), 1)}))
