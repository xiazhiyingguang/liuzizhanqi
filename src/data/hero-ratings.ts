/**
 * 七维评分的最后一维「成长」＝越打越强：
 * 层数/资源可累积且不随时间衰减、击杀带来永久增益、拖得越久战力越高者给高分；
 * 数值全程恒定的面板型、以及"攒了就要花"的循环消耗型资源给低分。
 * 参考刻度：10＝永久成长无上限；8~9＝多套成型叠层，后期判若两人；
 * 6~7＝有叠层但有上限或会被周期消耗；4~5＝仅轻微积累；1~3＝全程恒定或越拖越弱。
 */
function ratings(
    output: number,
    survival: number,
    mobility: number,
    control: number,
    support: number,
    coverage: number,
    growth: number
): HeroAbilityRatings {
    return {
        输出: output,
        生存: survival,
        机动: mobility,
        控制: control,
        支援: support,
        覆盖: coverage,
        成长: growth,
    };
}

