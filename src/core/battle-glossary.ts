export function tokenizeBattleGlossaryText(text: string): BattleGlossaryToken[] {
    if (!text) return [];

    const tokens: BattleGlossaryToken[] = [];
    let plainText = '';
    let cursor = 0;

    const flushPlainText = () => {
        if (!plainText) return;
        tokens.push({ text: plainText });
        plainText = '';
    };

    while (cursor < text.length) {
        const glossary = BATTLE_GLOSSARY.find(candidate => text.startsWith(candidate.term, cursor));
        if (!glossary) {
            plainText += text[cursor];
            cursor++;
            continue;
        }

        flushPlainText();
        tokens.push({ text: glossary.term, glossary });
        cursor += glossary.term.length;
    }

    flushPlainText();
    return tokens;
}
